# -*- coding: utf-8 -*-

__version__ = "1.0.0"  # Нужно для сборки APK

from kivy.app import App
from kivy.uix.boxlayout import BoxLayout
from kivy.uix.label import Label
from kivy.uix.button import Button
from kivy.core.window import Window

# Устанавливаем цвет фона окна (опционально)
Window.clearcolor = (0.95, 0.95, 0.95, 1)  # Светло-серый фон


class MyFirstApp(App):
    """
    Главный класс приложения.
    Наследуется от App — базового класса Kivy.
    """

    def build(self):
        """
        Метод build() вызывается автоматически при запуске приложения.
        Здесь мы создаём интерфейс и возвращаем его.
        """

        # ---------------------------------------------------------------------
        # 1. Создаём контейнер для всех элементов
        # ---------------------------------------------------------------------
        # BoxLayout — располагает элементы друг за другом
        # orientation="vertical" — сверху вниз
        # padding=30 — отступы от краёв экрана
        # spacing=20 — расстояние между элементами
        screen = BoxLayout(
            orientation="vertical",
            padding=30,
            spacing=20
        )

        # ---------------------------------------------------------------------
        # 2. Создаём заголовок
        # ---------------------------------------------------------------------
        # Label — текстовый элемент
        # text — сам текст
        # font_size — размер шрифта
        # color — цвет текста (R, G, B, A)
        # size_hint — относительный размер (ширина, высота)
        # size_hint_y — относительная высота (None = фиксированная)
        self.title_label = Label(
            text="Моё первое приложение",
            font_size=40,
            color=(0.2, 0.2, 0.8, 1),  # Синий цвет
            size_hint_y=None,
            height=80
        )

        # ---------------------------------------------------------------------
        # 3. Создаём информационный текст
        # ---------------------------------------------------------------------
        self.info_label = Label(
            text="Нажми на кнопку ниже",
            font_size=24,
            color=(0.1, 0.1, 0.1, 1),  # Почти чёрный
            size_hint_y=None,
            height=60
        )

        # ---------------------------------------------------------------------
        # 4. Создаём кнопку
        # ---------------------------------------------------------------------
        # Button — кнопка для нажатия
        # background_color — цвет кнопки (R, G, B, A)
        # size_hint=(1, 0.3) — ширина = 100% экрана, высота = 30% экрана
        start_button = Button(
            text="Нажми на меня",
            font_size=28,
            size_hint=(1, 0.3),
            background_color=(0.2, 0.6, 0.2, 1),  # Зелёный
            color=(1, 1, 1, 1)  # Белый текст
        )

        # Привязываем событие "нажатие" к функции button_clicked
        start_button.bind(on_press=self.button_clicked)

        # ---------------------------------------------------------------------
        # 5. Добавляем все элементы в контейнер
        # ---------------------------------------------------------------------
        # Порядок добавления важен: сначала будет верхний элемент
        screen.add_widget(self.title_label)
        screen.add_widget(self.info_label)
        screen.add_widget(start_button)

        # ---------------------------------------------------------------------
        # 6. Возвращаем готовый экран
        # ---------------------------------------------------------------------
        return screen

    def button_clicked(self, button):
        """
        Эта функция вызывается при нажатии на кнопку.
        Меняет текст информационной надписи.
        """
        self.info_label.text = "✅ Кнопка работает! 🎉"
        # Можно менять цвет или размер текста:
        # self.info_label.color = (0, 0.8, 0, 1)  # Зелёный цвет


# -----------------------------------------------------------------------------
# ТОЧКА ВХОДА — запуск приложения
# -----------------------------------------------------------------------------
# Этот блок выполняется только если файл запущен напрямую,
# а не импортирован как модуль
if __name__ == "__main__":
    MyFirstApp().run()
